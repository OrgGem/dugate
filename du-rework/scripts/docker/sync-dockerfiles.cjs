/** Compatibility Dockerfile paths are generated from the canonical root file. */
const fs = require('node:fs');
const path = require('node:path');
const { SERVICES } = require('./build-runtime.cjs');
const root = path.resolve(__dirname, '../..');
const canonical = fs.readFileSync(path.join(root, 'Dockerfile'), 'utf8');
for (const [service, dir] of Object.entries(SERVICES)) {
  fs.writeFileSync(path.join(root, dir, 'Dockerfile'), canonical + `\n# Generated by scripts/docker/sync-dockerfiles.cjs.\nFROM ${service} AS service\n`);
}
