const wrappers = ['docker-compose.yml', ...Object.values(SERVICES).map(dir => `${dir}/docker-compose.yml`)];
const cleanEnv = { ...process.env };
// Keep the model independent of the developer's shell env and credentials.
for (const entry of fs.readdirSync(path.join(root, 'compose'), { withFileTypes: true })) {
  if (!entry.isFile()) continue;
  const fragment = fs.readFileSync(path.join(root, 'compose', entry.name), 'utf8');
  for (const match of fragment.matchAll(/\$\{([A-Z][A-Z0-9_]*)/g)) delete cleanEnv[match[1]];
}
function compose(filename, environmentFile = envFile) {
  return spawnSync('docker', ['compose', '--profile', '*', '--env-file', environmentFile, '-f', filename, 'config', '--format', 'json'],
    { cwd: root, env: cleanEnv, encoding: 'utf8' });
}
for (const filename of wrappers) {
  test(`${filename}: model resolves builds, ports, startup order and shared networks`, () => {
    const normalized = filename.replaceAll('\\', '/');
    const standaloneFixture = standaloneFixtures.get(normalized);
    const result = compose(filename, standaloneFixture?.envPath ?? envFile);
    assert.equal(result.status, 0, result.stderr);
    const model = JSON.parse(result.stdout);
    if (standaloneFixture) {
      const workerName = normalized.split('/')[1].replace('.yml', '');
      assert.deepEqual(Object.keys(model.services), [workerName]);
      const worker = model.services[workerName];
      assert.equal(worker.container_name, undefined);
      assert.equal(path.resolve(worker.build.context), path.join(root, SERVICES[workerName]));
      assert.equal(worker.build.dockerfile, 'Dockerfile');
      assert.equal(worker.build.target, undefined);
      const workerDigestKey = {
        'document-core': 'DOCUMENT_CORE_IMAGE_DIGEST',
        'lc-checker': 'LC_IMAGE_DIGEST',
        'example-review': 'EXAMPLE_REVIEW_IMAGE_DIGEST',
      }[workerName];
      assert.equal(worker.image, standaloneFixture.workerEnvironment[workerDigestKey]);
      assert.equal(worker.depends_on, undefined);
      assert.equal(worker.ports, undefined);
      assert.equal(worker.environment.RUNTIME_URL, standaloneFixture.workerEnvironment.RUNTIME_URL
        ?? standaloneFixture.workerEnvironment.DOCUMENT_CORE_DOCKER_RUNTIME_URL);
      const workerTokenKey = {
        'document-core': 'DOCUMENT_CORE_RUNTIME_TOKEN',
        'lc-checker': 'LC_RUNTIME_TOKEN',
        'example-review': 'EXAMPLE_REVIEW_RUNTIME_TOKEN',
      }[workerName];
      assert.equal(worker.environment.RUNTIME_TOKEN, standaloneFixture.workerEnvironment[workerTokenKey]);
      assert.equal(worker.environment.REDIS_URL, standaloneFixture.workerEnvironment.REDIS_URL
        ?? standaloneFixture.workerEnvironment.DOCUMENT_CORE_DOCKER_REDIS_URL);
      if (workerName === 'document-core' || workerName === 'lc-checker') {
        assert.equal(worker.environment.CONNECTOR_URL, standaloneFixture.workerEnvironment.CONNECTOR_URL
          ?? standaloneFixture.workerEnvironment.DOCUMENT_CORE_DOCKER_CONNECTOR_URL);
        assert.equal(worker.environment.CONNECTOR_SERVICE_TOKEN, standaloneFixture.workerEnvironment.CONNECTOR_SERVICE_TOKEN);
      } else {
        assert.equal(worker.environment.CONNECTOR_URL, undefined);
        assert.equal(worker.environment.CONNECTOR_SERVICE_TOKEN, undefined);
      }
      assert.equal(model.networks['du-worker-net'].external, true);
      const dockerignore = fs.readFileSync(path.join(root, SERVICES[workerName], '.dockerignore'), 'utf8');
      assert.match(dockerignore, /^\.env\*/m);
      return;
    }
    assert.equal(model.services.postgres.ports, undefined);
    assert.equal(model.services.valkey.ports, undefined);
    for (const [name, service] of Object.entries(model.services)) {
      assert.equal(service.container_name, undefined);
      if (service.build) {
        const platformService = {
          orchestrator: 'orchestrator',
          'orchestrator-migrate': 'orchestrator',
          connector: 'connector',
          'connector-migrate': 'connector',
        }[name];
        const expectedContext = standaloneWorkers.has(name)
          ? path.join(root, 'businesses', name)
          : path.join(root, 'orchestrator');
        assert.equal(path.resolve(service.build.context), expectedContext);
        assert.equal(service.build.dockerfile, platformService ? `services/${platformService}/Dockerfile` : 'Dockerfile');
        assert.equal(service.build.target, undefined);
      }
      const localImageNames = {
        orchestrator: 'du-orchestrator:local',
        connector: 'du-connector:local',
        'document-core': 'du-document-core:local',
        'lc-checker': 'du-lc-checker:local',
        'example-review': 'du-example-review:local',
      };
      if (localImageNames[name]) assert.equal(service.image, localImageNames[name]);
      if (name === 'orchestrator-migrate') assert.equal(service.image, 'du-orchestrator:local');
      if (name === 'connector-migrate') assert.equal(service.image, 'du-connector:local');
      if (service.ports) {
        for (const port of service.ports) assert.equal(port.host_ip, '127.0.0.1');
        if (name === 'orchestrator') {
          assert.equal(service.environment.PORT, '3000');
          assert.equal(service.environment.ORCHESTRATOR_PORT, '3000');
          assert.deepEqual(service.ports.map(p => [p.target, p.published]), [[3000, '24100'], [3001, '24101']]);
          assert.equal(service.environment.AUTO_MIGRATE, 'false');
          assert.equal(service.depends_on, undefined);
        }
        if (name === 'connector') {
          assert.equal(service.environment.PORT, '8080');
          assert.equal(service.environment.CONNECTOR_PORT, undefined);
          assert.equal(service.ports[0].published, '24180');
        }
      }
      if (name === 'document-core' || name === 'lc-checker') {
        const connector = model.services.connector;
        assert.ok(Object.keys(service.networks).some(n => Object.hasOwn(connector.networks, n)));
        assert.equal(service.environment.CONNECTOR_URL, 'http://connector:8080');
        assert.equal(service.depends_on, undefined);
      }
      if (['document-core', 'lc-checker', 'example-review'].includes(name)) {
        const identities = JSON.parse(model.services.orchestrator.environment.WORKER_IDENTITY_TOKENS_BY_BUSINESS);
        assert.equal(service.environment.RUNTIME_TOKEN, identities[name]);
        assert.notEqual(service.environment.RUNTIME_TOKEN, model.services.orchestrator.environment.ADMIN_TOKEN);
      }
    }
    if (filename === 'docker-compose.yml') {
      assert.deepEqual(Object.keys(model.services).sort(), [
        'connector', 'connector-db-init', 'connector-migrate', 'document-core', 'example-review',
        'lc-checker', 'orchestrator', 'orchestrator-migrate', 'postgres', 'valkey',
      ]);
      assert.deepEqual(model.services['orchestrator-migrate'].profiles, ['migration']);
      assert.deepEqual(model.services['connector-migrate'].profiles, ['migration']);
      assert.equal(model.services['orchestrator-migrate'].entrypoint.at(-1), '/app/dist/migrate-cli.js');
      assert.equal(model.services['connector-migrate'].entrypoint.at(-1), '/app/dist/migrate-cli.js');
      assert.equal(model.services['orchestrator-migrate'].image, model.services.orchestrator.image);
      assert.equal(model.services['connector-migrate'].image, model.services.connector.image);
    }
  });
}

test('deployment image references pin the digest advertised by each runtime identity', () => {
  const digests = {
    DU_ORCHESTRATOR_RUNTIME_IMAGE_DIGEST: 'registry.example/du/orchestrator@sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa',
    CONNECTOR_RUNTIME_IMAGE_DIGEST: 'registry.example/du/connector@sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb',
    DOCUMENT_CORE_IMAGE_DIGEST: 'registry.example/du/document-core@sha256:cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc',
    LC_IMAGE_DIGEST: 'registry.example/du/lc-checker@sha256:dddddddddddddddddddddddddddddddddddddddddddddddddddddddddddddddd',
    EXAMPLE_REVIEW_IMAGE_DIGEST: 'registry.example/du/example-review@sha256:eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee',
  };
  const digestEnvFile = path.join(temporary, 'digest.env');
  const generated = { ...localEnvironment(), DU_IMAGE_TAG: 'candidate', ...digests };
  fs.writeFileSync(digestEnvFile, Object.entries(generated).map(([key, value]) => `${key}=${value}`).join('\n'));
  const result = compose('docker-compose.yml', digestEnvFile);
  assert.equal(result.status, 0, result.stderr);
  const services = JSON.parse(result.stdout).services;
  const matchingImages = [
    ['orchestrator', 'orchestrator-migrate', 'DU_ORCHESTRATOR_RUNTIME_IMAGE_DIGEST'],
    ['connector', 'connector-migrate', 'CONNECTOR_RUNTIME_IMAGE_DIGEST'],
    ['document-core', undefined, 'DOCUMENT_CORE_IMAGE_DIGEST'],
    ['lc-checker', undefined, 'LC_IMAGE_DIGEST'],
    ['example-review', undefined, 'EXAMPLE_REVIEW_IMAGE_DIGEST'],
  ];
  for (const [serviceName, migrationName, digestName] of matchingImages) {
    assert.equal(services[serviceName].image, digests[digestName]);
    if (migrationName) assert.equal(services[migrationName].image, digests[digestName]);
  }
  assert.equal(services.orchestrator.environment.DU_ORCHESTRATOR_RUNTIME_IMAGE_DIGEST,
    services.orchestrator.image);
  assert.equal(services.connector.environment.CONNECTOR_RUNTIME_IMAGE_DIGEST,
    services.connector.image);
  assert.equal(services['document-core'].environment.IMAGE_DIGEST, services['document-core'].image);
  assert.equal(services['lc-checker'].environment.IMAGE_DIGEST, services['lc-checker'].image);
  assert.equal(services['example-review'].environment.IMAGE_DIGEST, services['example-review'].image);
});
