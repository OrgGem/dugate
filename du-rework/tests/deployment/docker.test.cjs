const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { spawnSync } = require('node:child_process');
const { createHmac } = require('node:crypto');
const { SERVICES, workspaceManifests, buildPlan, deploymentLockfile } = require('../../scripts/docker/build-runtime.cjs');
const { localEnvironment } = require('../../scripts/docker/init-env.cjs');
const root = path.resolve(__dirname, '../..');
const entries = workspaceManifests(root);
const standaloneWorkers = new Set(['document-core', 'lc-checker', 'example-review']);
function serviceEntries(service) {
  return standaloneWorkers.has(service)
    ? workspaceManifests(path.join(root, SERVICES[service]))
    : entries;
}

for (const [service, directory] of Object.entries(SERVICES)) {
  test(`${service}: runtime dependencies build before their consumers`, () => {
    const graph = serviceEntries(service);
    const plan = buildPlan(graph, `@du/${service}`);
    assert.equal(plan.at(-1), `@du/${service}`);
    for (const name of plan) {
      for (const [dependency, version] of Object.entries(graph.get(name).manifest.dependencies ?? {})) {
        if (version.startsWith('workspace:')) assert.ok(plan.indexOf(dependency) < plan.indexOf(name));
      }
    }
    // Connector is a worker SDK test dependency, and must never enter worker builds.
    if (directory.startsWith('businesses/')) assert.ok(!plan.includes('@du/connector'));
  });
  if (!standaloneWorkers.has(service)) {
    test(`${service}: legacy Dockerfile stays in sync with canonical target`, () => {
      const canonical = fs.readFileSync(path.join(root, 'Dockerfile'), 'utf8').replace(/\r\n/g, '\n');
      const generated = fs.readFileSync(path.join(root, directory, 'Dockerfile'), 'utf8').replace(/\r\n/g, '\n');
      assert.equal(generated, `${canonical}\n# Generated by scripts/docker/sync-dockerfiles.cjs.\nFROM ${service} AS service\n`);
    });
  } else {
    test(`${service}: standalone Dockerfile has its own runnable image`, () => {
      const dockerfile = fs.readFileSync(path.join(root, directory, 'Dockerfile'), 'utf8');
      assert.match(dockerfile, /CMD\s+\[\s*"node"\s*,\s*"dist\/main\.js"\s*\]/);
      assert.doesNotMatch(dockerfile, /Generated by scripts\/docker\/sync-dockerfiles\.cjs/);
    });
  }
}

test('build planner refuses dependency cycles and missing workspace packages', () => {
  const graph = new Map([
    ['a', { manifest: { dependencies: { b: 'workspace:*' } } }],
    ['b', { manifest: { dependencies: { a: 'workspace:*' } } }],
  ]);
  assert.throws(() => buildPlan(graph, 'a'), /cycle/);
  graph.delete('b');
  assert.throws(() => buildPlan(graph, 'a'), /Missing workspace dependency/);
});

test('portable deployment preserves every locked version and importer', () => {
  const original = fs.readFileSync(path.join(root, 'pnpm-lock.yaml'), 'utf8');
  const prepared = deploymentLockfile(original, root);
  const lockContents = value => value.slice(value.indexOf('overrides:'))
    .replace(/tarball: file:[^,}\r\n]+/g, 'tarball: file:<local-artifact>');
  assert.equal(lockContents(prepared), lockContents(original));
  assert.ok(prepared.includes(path.resolve(root, 'orchestrator/vendor/xlsx-0.20.3.tgz').split(path.sep).join('/')));
  assert.equal(deploymentLockfile(prepared, root), prepared);
  assert.throws(() => deploymentLockfile('lockfileVersion: 9\n'), /settings are missing/);
});

test('local credentials encode identical grant bytes and signed, expiring identity', () => {
  const env = localEnvironment(1700000000000);
  assert.equal(Buffer.byteLength(env.INVOCATION_GRANT_SECRET), 32);
  assert.deepEqual(Buffer.from(env.INVOCATION_GRANT_SECRET), Buffer.from(env.CONNECTOR_INVOCATION_GRANT_SECRET, 'base64'));
  assert.notEqual(env.RUNTIME_TOKEN, env.ADMIN_TOKEN);
  const [header, payload, signature] = env.CONNECTOR_SERVICE_TOKEN.split('.');
  assert.equal(signature, createHmac('sha256', Buffer.from(env.SERVICE_IDENTITY_SECRET, 'base64'))
    .update(`${header}.${payload}`).digest('base64url'));
  const claims = JSON.parse(Buffer.from(payload, 'base64url'));
  assert.equal(claims.aud, 'connector');
  assert.deepEqual(claims.scopes, ['connector:invoke']);
  assert.equal(claims.exp, 1700000000 + 86400);
});

const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'du-compose-regression-'));
const envFile = path.join(temporary, 'test.env');
fs.writeFileSync(envFile, Object.entries({ ...localEnvironment(), COST_CONTROL_CONNECTOR_TOKEN: 'compose-test-cost-control-token', ORCHESTRATOR_PORT: '24100',
  ADMIN_SHELL_PORT: '24101', CONNECTOR_PORT: '24180' }).map(([k, v]) => `${k}=${v}`).join('\n'));
const emptyEnvFile = path.join(temporary, 'empty.env');
fs.writeFileSync(emptyEnvFile, '');
const standaloneFixtures = new Map();
for (const name of ['lc-checker', 'example-review']) {
  const workerRoot = path.join(root, SERVICES[name]);
  const envPath = path.join(temporary, `${name}.env`);
  const workerEnvironment = {
    RUNTIME_URL: 'http://host.docker.internal:3002/api/runtime/v1',
    RUNTIME_TOKEN: `test-${name}-worker-token`,
    REDIS_URL: 'redis://host.docker.internal:16380',
  };
  if (name === 'lc-checker') {
    workerEnvironment.CONNECTOR_URL = 'http://host.docker.internal:8088';
    workerEnvironment.CONNECTOR_SERVICE_TOKEN = 'test-connector-invoke-token';
  }
  fs.writeFileSync(envPath, Object.entries(workerEnvironment).map(([key, value]) => `${key}=${value}`).join('\n'));

  const sourceComposePath = path.join(workerRoot, 'docker-compose.yml');
  const sourceCompose = fs.readFileSync(sourceComposePath, 'utf8');
  const absoluteContext = JSON.stringify(workerRoot.split(path.sep).join('/'));
  const absoluteEnvFile = JSON.stringify(envPath.split(path.sep).join('/'));
  const fixtureCompose = sourceCompose
    .replace(/(^\s*context:\s*)\.\s*$/m, `$1${absoluteContext}`)
    .replace(/(^\s*-\s*)\.env\.docker\.local\s*$/m, `$1${absoluteEnvFile}`);
  assert.notEqual(fixtureCompose, sourceCompose, `${name} Compose fixture rewrites the local context and env file`);
  const composePath = path.join(temporary, `${name}.compose.yml`);
  fs.writeFileSync(composePath, fixtureCompose);
  standaloneFixtures.set(`businesses/${name}/docker-compose.yml`, {
    composePath,
    workerEnvironment,
  });
}
const wrappers = ['docker-compose.yml', ...Object.values(SERVICES).map(dir => `${dir}/docker-compose.yml`)];
const cleanEnv = { ...process.env };
// Keep the model independent of the developer's shell env and credentials.
for (const entry of fs.readdirSync(path.join(root, 'compose'), { withFileTypes: true })) {
  if (!entry.isFile()) continue;
  const fragment = fs.readFileSync(path.join(root, 'compose', entry.name), 'utf8');
  for (const match of fragment.matchAll(/\$\{([A-Z][A-Z0-9_]*)/g)) delete cleanEnv[match[1]];
}
function compose(filename, environmentFile = envFile) {
  return spawnSync('docker', ['compose', '--env-file', environmentFile, '-f', filename, 'config', '--format', 'json'],
    { cwd: root, env: cleanEnv, encoding: 'utf8' });
}
for (const filename of wrappers) {
  test(`${filename}: model resolves builds, ports, startup order and shared networks`, () => {
    const standaloneFixture = standaloneFixtures.get(filename.replaceAll('\\', '/'));
    const result = standaloneFixture
      ? compose(standaloneFixture.composePath, emptyEnvFile)
      : compose(filename);
    assert.equal(result.status, 0, result.stderr);
    const model = JSON.parse(result.stdout);
    if (standaloneFixture) {
      const workerName = filename.split('/')[1];
      assert.deepEqual(Object.keys(model.services), [workerName]);
      const worker = model.services[workerName];
      assert.equal(worker.container_name, undefined);
      assert.equal(path.resolve(worker.build.context), path.join(root, SERVICES[workerName]));
      assert.equal(worker.build.dockerfile, 'Dockerfile');
      assert.equal(worker.build.target, undefined);
      assert.equal(worker.depends_on, undefined);
      assert.equal(worker.ports, undefined);
      assert.equal(worker.environment.NODE_ENV, 'production');
      assert.equal(worker.environment.PORT, '0');
      assert.equal(worker.environment.RUNTIME_URL, standaloneFixture.workerEnvironment.RUNTIME_URL);
      assert.equal(worker.environment.RUNTIME_TOKEN, standaloneFixture.workerEnvironment.RUNTIME_TOKEN);
      assert.equal(worker.environment.REDIS_URL, standaloneFixture.workerEnvironment.REDIS_URL);
      if (workerName === 'lc-checker') {
        assert.equal(worker.environment.CONNECTOR_URL, standaloneFixture.workerEnvironment.CONNECTOR_URL);
        assert.equal(worker.environment.CONNECTOR_SERVICE_TOKEN, standaloneFixture.workerEnvironment.CONNECTOR_SERVICE_TOKEN);
      } else {
        assert.equal(worker.environment.CONNECTOR_URL, undefined);
        assert.equal(worker.environment.CONNECTOR_SERVICE_TOKEN, undefined);
      }
      const dockerignore = fs.readFileSync(path.join(root, SERVICES[workerName], '.dockerignore'), 'utf8');
      assert.match(dockerignore, /^\.env\*/m);
      return;
    }
    assert.equal(model.services.postgres.ports, undefined);
    assert.equal(model.services.valkey.ports, undefined);
    for (const [name, service] of Object.entries(model.services)) {
      assert.equal(service.container_name, undefined);
      if (service.build) {
        const expectedContext = standaloneWorkers.has(name) ? path.join(root, 'businesses', name) : root;
        assert.equal(path.resolve(service.build.context), expectedContext);
        assert.equal(service.build.dockerfile, 'Dockerfile');
        if (standaloneWorkers.has(name)) assert.equal(service.build.target, undefined);
        else assert.ok(Object.hasOwn(SERVICES, service.build.target));
      }
      if (service.ports) {
        for (const port of service.ports) assert.equal(port.host_ip, '127.0.0.1');
        if (name === 'orchestrator') {
          assert.equal(service.environment.PORT, '3000');
          assert.equal(service.environment.ORCHESTRATOR_PORT, '3000');
          assert.deepEqual(service.ports.map(p => [p.target, p.published]), [[3000, '24100'], [3001, '24101']]);
          assert.equal(service.depends_on.migrate.condition, 'service_completed_successfully');
          assert.equal(service.environment.AUTO_MIGRATE, 'false');
        }
        if (name === 'connector') {
          assert.equal(service.environment.PORT, '8080');
          assert.equal(service.environment.CONNECTOR_PORT, undefined);
          assert.equal(service.ports[0].published, '24180');
        }
      }
      if (name === 'document-core' || name === 'lc-checker') {
        const connector = model.services.connector;
        assert.ok(Object.keys(service.networks).some(n => Object.hasOwn(connector.networks, n)));
        assert.equal(service.environment.CONNECTOR_URL, 'http://connector:8080');
        assert.equal(service.depends_on.connector.condition, 'service_healthy');
      }
      if (['document-core', 'lc-checker', 'example-review'].includes(name)) {
        const identities = JSON.parse(model.services.orchestrator.environment.WORKER_IDENTITY_TOKENS_BY_BUSINESS);
        assert.equal(service.environment.RUNTIME_TOKEN, identities[name]);
        assert.notEqual(service.environment.RUNTIME_TOKEN, model.services.orchestrator.environment.ADMIN_TOKEN);
      }
    }
    if (filename === 'docker-compose.yml') {
      assert.deepEqual(Object.keys(model.services).sort(), [
        'connector', 'connector-db-init', 'document-core', 'example-review', 'lc-checker',
        'migrate', 'orchestrator', 'postgres', 'valkey',
      ]);
    }
  });
}
test('missing secrets refuse startup instead of using sample production passwords', () => {
  const result = compose('docker-compose.yml', emptyEnvFile);
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /POSTGRES_PASSWORD/);
});

process.on('exit', () => {
  fs.unlinkSync(envFile);
  for (const file of [emptyEnvFile, ...[...standaloneFixtures.values()].flatMap(({ composePath }) => [composePath])]) {
    if (fs.existsSync(file)) fs.unlinkSync(file);
  }
  for (const name of ['lc-checker', 'example-review']) {
    const fixtureEnv = path.join(temporary, `${name}.env`);
    if (fs.existsSync(fixtureEnv)) fs.unlinkSync(fixtureEnv);
  }
  fs.rmdirSync(temporary);
});
